// Build: compiles the JSX in src/index.src.html to plain JS and writes index.html.
// Usage: npm install && npm run build
const fs = require('fs');
const path = require('path');
const Babel = require('@babel/standalone');

const SRC = path.join(__dirname, 'src', 'index.src.html');
const OUT = path.join(__dirname, 'index.html');
const src = fs.readFileSync(SRC, 'utf8');

let n = 0;
const out = src.replace(/<script type="text\/babel">([\s\S]*?)<\/script>/g, (_, code) => {
  n++;
  const res = Babel.transform(code, { presets: ['react'], sourceType: 'script', compact: false, comments: false, retainLines: false });
  return '<script>\n' + res.code + '\n</script>';
});
if (/text\/babel/.test(out)) throw new Error('Untransformed text/babel block left');
const banner = '<!-- GENERATED by build.js from src/index.src.html. Edit the source, then run: npm run build -->\n';
fs.writeFileSync(OUT, out.replace(/^<!DOCTYPE html>\n?/i, '<!DOCTYPE html>\n' + banner));
console.log(`Built index.html (${n} JSX blocks compiled, ${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
